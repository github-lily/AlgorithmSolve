SELECT YEAR(t1.DIFFERENTIATION_DATE) AS YEAR, t2.MAX_SIZE-t1.SIZE_OF_COLONY AS YEAR_DEV, t1.ID
FROM ECOLI_DATA t1
JOIN (  SELECT YEAR(DIFFERENTIATION_DATE) AS BIRTH_YEAR, 
               MAX(SIZE_OF_COLONY) AS MAX_SIZE 
          FROM ECOLI_DATA 
      GROUP BY BIRTH_YEAR) t2 
  ON YEAR(t1.DIFFERENTIATION_DATE) = t2.BIRTH_YEAR
ORDER BY YEAR ASC, YEAR_DEV ASC;