def solution(n):
    # 0에서 시작하지 않고 n에서 역방향 탐색
    def dfs(num):
        if num == 0:
            return 0

        if num % 2 == 0:
            return dfs(num // 2)

        return dfs(num - 1) + 1

    return dfs(n)    
    
